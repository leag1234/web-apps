    var esc = function (s) { return Common.Utils.String.htmlEncode(s == null ? '' : String(s)); };
    var PROP_SOURCES = 'ElixirSources', PROP_STYLE = 'ElixirCitationStyle';
    var TAG_CITE = 'elixir-cite:', TAG_BIB = 'elixir-bibliography', TAG_INDEX = 'elixir-index';
    // builder helper: a content control emptied by RemoveAllElements keeps one empty paragraph
    var TRIM0 = 'var trim0 = function (c) { if (c.GetElementsCount() > 1) { var e0 = c.GetElement(0); if (e0 && e0.GetText && !e0.GetText().replace(/\\s/g, "")) c.RemoveElement(0); } };';

    // ---- citation styles (pure functions, also used by the tests) ------------------------------------
    var Styles = window.ElixirCitationStyles = {
        // "Last, First; Last2, First2" -> [{last, first}]
        authors: function (s) {
            return _.compact(_.map((s || '').split(';'), function (a) {
                a = a.trim(); if (!a) return null;
                var p = a.split(','), last = (p[0] || '').trim(), first = (p.slice(1).join(',') || '').trim();
                if (p.length === 1) { var w = a.split(/\s+/); last = w.pop(); first = w.join(' '); }
                return {last: last, first: first};
            }));
        },
        initials: function (first) {
            return _.map(_.compact((first || '').split(/[\s-]+/)), function (n) { return n.charAt(0).toUpperCase() + '.'; }).join(' ');
        },
        // in-text citation
        cite: function (style, src) {
            var a = this.authors(src.author), n = a.length, year = src.year || 'n.d.';
            var who = !n ? (src.title || '') : n === 1 ? a[0].last : n === 2 ? a[0].last + (style === 'mla' ? ' and ' : ' & ') + a[1].last : a[0].last + ' et al.';
            if (style === 'mla') return '(' + who + (src.pages ? ' ' + src.pages : '') + ')';
            return '(' + who + ', ' + year + ')';
        },
        // bibliography entry: array of [text, italic]
        entry: function (style, src) {
            var a = this.authors(src.author), me = this, out = [], t = function (s, i) { s && out.push([s, !!i]); };
            var type = src.type || 'book', year = src.year || 'n.d.', title = src.title || '';
            if (style === 'mla') {
                var names = !a.length ? '' : a.length === 1 ? a[0].last + (a[0].first ? ', ' + a[0].first : '') :
                    a.length === 2 ? a[0].last + ', ' + a[0].first + ', and ' + (a[1].first ? a[1].first + ' ' : '') + a[1].last : a[0].last + ', ' + a[0].first + ', et al';
                names && t(names.replace(/\.$/, '') + '. ');
                if (type === 'book') { t(title, true); t('. '); t([src.publisher, year].filter(Boolean).join(', ') + '.'); }
                else if (type === 'article') { t('“' + title + '.” '); t(src.container, true); t(', ' + [src.volume ? 'vol. ' + src.volume : '', year, src.pages ? 'pp. ' + src.pages : ''].filter(Boolean).join(', ') + '.'); }
                else { t('“' + title + '.” '); t(src.container, true); t(', ' + [year, src.url].filter(Boolean).join(', ') + '.'); }
                return out;
            }
            // APA 7th
            var list = _.map(a, function (x) { return x.last + (x.first ? ', ' + me.initials(x.first) : ''); });
            var names2 = list.length <= 1 ? (list[0] || '') : list.slice(0, -1).join(', ') + ', & ' + list[list.length - 1];
            names2 && t(names2 + ' ');
            t('(' + year + '). ');
            if (type === 'book') { t(title, true); t('. '); src.publisher && t(src.publisher + '.'); }
            else if (type === 'article') { t(title + '. '); t(src.container, true); t((src.volume ? ', ' + src.volume : '') + (src.pages ? ', ' + src.pages : '') + '.'); }
            else { t(title, true); t('. '); src.container && t(src.container + '. '); src.url && t(src.url); }
            return out;
        },
        sortKey: function (src) { var a = this.authors(src.author); return ((a[0] && a[0].last) || src.title || '').toLowerCase(); },
        heading: function (style) { return style === 'mla' ? 'Works Cited' : 'References'; }
    };

